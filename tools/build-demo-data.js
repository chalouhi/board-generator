#!/usr/bin/env node
// Writes demo/samples.js and demo/fonts.js from samples/ and fonts/, so the
// demo page has everything with the page and asks no server for anything
// afterwards (requirement 26). Run after changing a sample or a font:
//   node tools/build-demo-data.js
// The tests check that both files are up to date.
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

const SAMPLES = [
  ['1-smallest.json', '1 · Smallest', 'The least a file can contain: three columns, three cards.'],
  ['2-comprehensive.json', '2 · Comprehensive', 'A strip, kinds, groups, due dates, a passed limit, "45 more", links and buttons.'],
  ['3-many-columns.json', '3 · Many columns', 'Eight columns that wrap into two rows, long titles, an empty column.'],
  ['4-custom-colours.json', '4 · Custom colours', 'A green colour set and two lines per card.'],
  ['5-broken.json', '5 · Broken', 'Ten mistakes: nothing is drawn and all ten are listed.'],
];

function samplesJS() {
  const list = SAMPLES.map(([file, label, why]) => ({ file, label, why, text: fs.readFileSync(path.join(ROOT, 'samples', file), 'utf8') }));
  return '// Generated by tools/build-demo-data.js from samples/. Do not edit.\n' +
    'window.BOARD_SAMPLES = ' + JSON.stringify(list, null, 1) + ';\n';
}
function fontsJS() {
  const b64 = f => fs.readFileSync(path.join(ROOT, 'fonts', f)).toString('base64');
  return '// Generated by tools/build-demo-data.js from fonts/ (Carlito, SIL Open Font Licence 1.1). Do not edit.\n' +
    `window.BOARD_FONTS = {regular: "${b64('Carlito-Regular.ttf')}",\nbold: "${b64('Carlito-Bold.ttf')}"};\n`;
}

if (require.main === module) {
  fs.writeFileSync(path.join(ROOT, 'demo', 'samples.js'), samplesJS());
  fs.writeFileSync(path.join(ROOT, 'demo', 'fonts.js'), fontsJS());
  console.log('wrote demo/samples.js and demo/fonts.js');
}
module.exports = { samplesJS, fontsJS, SAMPLES };
